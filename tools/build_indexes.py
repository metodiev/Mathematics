def learning_paths_page(disciplines: list[dict]) -> str:
    paths_file = ROOT / "tools" / "learning_paths.json"
    data = json.loads(paths_file.read_text(encoding="utf-8"))
    lookup: dict[str, tuple[dict, dict]] = {}
    for d in disciplines:
        for t in d["topics"]:
            lookup[f"{d['id']}/{t['slug']}"] = (d, t)

    def render(ref: str) -> str:
        d, t = lookup[ref]
        status, _ = topic_status(ROOT / d["id"] / t["slug"])
        if status == STATUS_PLANNED:
            return f"{t['title']} *(planned)*"
        return f"[{t['title']}]({ref}/README.md)"

    def stage_hours(refs: list[str]) -> int:
        return sum(lookup[r][1]["hours"] for r in refs if r in lookup)

    out: list[str] = []
    out.append("<!-- Generated by tools/build_indexes.py from tools/learning_paths.json. Do not edit by hand. -->")
    out.append("")
    out.append("# Learning Paths")
    out.append("")
    out.append("Mathematics is not a single sequence, and nobody learns all of it. These are curated routes")
    out.append("through the repository: choose by destination, not by discipline. Topics marked *(planned)* are")
    out.append("part of the curriculum but not written yet — read the closest available prerequisite first, and")
    out.append("check the [Roadmap](ROADMAP.md) for progress.")
    out.append("")
    out.append("## Where do I start?")
    out.append("")
    out.append("Find the first statement that describes you and follow its advice.")
    out.append("")
    out.append("| If this sounds like you | Then |")
    out.append("|---|---|")
    for condition, advice in DIAGNOSTIC:
        out.append(f"| {condition} | {advice} |")
    out.append("")
    out.append("A second, sharper diagnostic: open a tutorial one level above where you think you are and")
    out.append("attempt the **Beginner** exercises. If you score below about 70%, the level below is where you")
    out.append("belong — and doing it quickly will cost you less time than struggling upward.")
    out.append("")
    out.append("```mermaid")
    out.append("flowchart LR")
    out.append('    A["Numbers"] --> B["Algebra"]')
    out.append('    B --> C["Functions"]')
    out.append('    C --> D["Calculus"]')
    out.append('    B --> E["Geometry and Trigonometry"]')
    out.append('    E --> D')
    out.append('    D --> F["Analysis and Differential Equations"]')
    out.append('    B --> G["Linear Algebra and Discrete Mathematics"]')
    out.append('    G --> H["Probability, Statistics, Optimization"]')
    out.append('    F --> I["Topology, Algebra, Research Topics"]')
    out.append("```")
    out.append("")

    for path in data["paths"]:
        refs = [r for stage in path["stages"] for r in stage["topics"]]
        out.append(f"## {path['title']}")
        out.append("")
        out.append(f"**For:** {path['audience']}")
        out.append("")
        out.append(path["intro"])
        out.append("")
        out.append(f"**Estimated total:** ~{stage_hours(refs)} hours of study, {len(refs)} topics.")
        out.append("")
        for stage in path["stages"]:
            out.append(f"### {stage['name']}")
            out.append("")
            if stage.get("note"):
                out.append(f"*{stage['note']}*")
                out.append("")
            for ref in stage["topics"]:
                if ref in lookup:
                    out.append(f"- {render(ref)}")
            out.append("")
            out.append(f"*Stage time: ~{stage_hours(stage['topics'])} hours.*")
            out.append("")

    out.append("## Short routes")
    out.append("")
    out.append("When you need one subject and nothing else.")
    out.append("")
    for route in data["shortRoutes"]:
        out.append(f"### {route['title']}")
        out.append("")
        out.append(f"*{route['note']}*")
        out.append("")
        for ref in route["topics"]:
            if ref in lookup:
                out.append(f"- {render(ref)}")
        out.append(f"\n*About {stage_hours(route['topics'])} hours.*")
        out.append("")

    out.append("## How to study a topic")
    out.append("")
    out.append("1. **Read the intuition section first**, before any symbols. If it does not land, read it")
    out.append("   again after the formal definitions — that order is deliberate.")
    out.append("2. **Reproduce every worked example on paper**, without looking. Reading a proof is not the")
    out.append("   same as being able to write it.")
    out.append("3. **Do the exercises before the solutions.** Begin at the Beginner level even if the tutorial")
    out.append("   felt easy; fluency is the point.")
    out.append("4. **Write the summary from memory** at the end. If you cannot, the topic is not finished.")
    out.append("5. **Revisit after a week.** Spaced retrieval is what converts understanding into knowledge.")
    out.append("")
    out.append("## If you get stuck")
    out.append("")
    out.append("* A definition is unclear: find the tutorial that *introduces* it using the prerequisites")
    out.append("  section — do not try to absorb it from its use.")
    out.append("* A proof does not convince you: write out the quantifiers explicitly and check each implication")
    out.append("  separately. Most confusion in proofs is a missing quantifier.")
    out.append("* An exercise resists: solve a smaller case by hand, then generalise.")
    out.append("* You can follow everything but cannot reproduce it: the gap is fluency, not understanding.")
    out.append("  Do more Beginner-level exercises.")
    out.append("")
    return "\n".join(out) + "\n"


def main() -> int:
    disciplines = load()
    written = 0
    for d in disciplines:
        target = ROOT / d["id"] / "README.md"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(discipline_page(d), encoding="utf-8")
        written += 1
    (ROOT / "ROADMAP.md").write_text(roadmap(disciplines), encoding="utf-8")
    written += 1
    if (ROOT / "tools" / "learning_paths.json").exists():
        (ROOT / "LEARNING_PATHS.md").write_text(learning_paths_page(disciplines), encoding="utf-8")
        written += 1
    print(f"Wrote {written} index files.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
